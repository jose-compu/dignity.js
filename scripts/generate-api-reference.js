#!/usr/bin/env node
/**
 * Generate docs/api-reference.md from docs/openapi-like.json (#93).
 * Source of truth: openapi-like.json (validated by tests/unit/openapi-like.test.js).
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const specPath = path.join(root, 'docs/openapi-like.json');
const outPath = path.join(root, 'docs/api-reference.md');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const spec = JSON.parse(fs.readFileSync(specPath, 'utf8'));

function heading(level, text) {
  return `${'#'.repeat(level)} ${text}\n\n`;
}

function table(headers, rows) {
  const lines = [
    `| ${headers.join(' | ')} |`,
    `| ${headers.map(() => '---').join(' | ')} |`
  ];
  for (const row of rows) {
    lines.push(`| ${row.join(' | ')} |`);
  }
  return `${lines.join('\n')}\n\n`;
}

function formatEntry(key, entry) {
  if (typeof entry === 'string') {
    return `- **\`${key}\`** — ${entry}`;
  }
  if (entry && entry.method) {
    const opts = entry.options
      ? `\n  - Options: ${typeof entry.options === 'object'
        ? Object.entries(entry.options).map(([k, v]) => `\`${k}\`: ${v}`).join('; ')
        : entry.options}`
      : '';
    const extra = [
      entry.description ? `\n  - ${entry.description}` : '',
      entry.owner ? `\n  - Owner: ${entry.owner}` : '',
      entry.authorization ? `\n  - Authorization: ${entry.authorization}` : '',
      entry.returns ? `\n  - Returns: ${entry.returns}` : '',
      opts
    ].join('');
    return `- **\`${entry.method}\`**${extra}`;
  }
  return `- **\`${key}\`** — ${JSON.stringify(entry)}`;
}

function sectionResources(title, resources) {
  let out = heading(3, title);
  for (const [key, entry] of Object.entries(resources || {})) {
    if (typeof entry === 'object' && !entry.method && !Array.isArray(entry)) {
      out += heading(4, key);
      out += `${Object.entries(entry).map(([k, v]) => formatEntry(k, v)).join('\n')}\n\n`;
    } else {
      out += `${formatEntry(key, entry)}\n`;
    }
  }
  out += '\n';
  return out;
}

function buildMarkdown() {
  const lines = [];
  lines.push(`<!-- Generated by scripts/generate-api-reference.js — do not edit by hand -->`);
  lines.push('');
  lines.push(heading(1, `dignity.js API reference (v${spec.version})`));
  lines.push(`${spec.description}.\n\n`);
  lines.push(`> Generated from [\`docs/openapi-like.json\`](./openapi-like.json). Regenerate: \`npm run docs:api-reference\`.\n\n`);

  lines.push(heading(2, 'DignityP2P lifecycle'));
  lines.push(`${Object.entries(spec.lifecycle || {}).map(([k, v]) => `- **\`${k}()\`** — ${v}`).join('\n')}\n\n`);

  lines.push(sectionResources('Object CRUD (`collections/{collection}/{id}`)', spec.resources['collections/{collection}/{id}']));
  lines.push(sectionResources('Collection queries (`collections/{collection}`)', spec.resources['collections/{collection}']));

  for (const section of ['peers', 'identity', 'peerGroups']) {
    lines.push(sectionResources(section.charAt(0).toUpperCase() + section.slice(1), spec.resources[section]));
  }

  if (spec.resources.cqrs) {
    lines.push(heading(3, 'CQRS'));
    lines.push(`${Object.entries(spec.resources.cqrs).map(([k, v]) => `- **\`${k}\`** — ${v}`).join('\n')}\n\n`);
  }

  lines.push(heading(2, 'Events'));
  lines.push(table(['Event', 'Description'], Object.entries(spec.events || {}).map(([k, v]) => [`\`${k}\``, v])));

  lines.push(heading(2, 'Record shape'));
  lines.push(heading(3, 'Active record'));
  lines.push('```json\n');
  lines.push(JSON.stringify(spec.recordShape.active, null, 2));
  lines.push('\n```\n\n');
  if (spec.recordShape.deletedStub) {
    lines.push(heading(3, 'Deleted stub'));
    lines.push('```json\n');
    lines.push(JSON.stringify(spec.recordShape.deletedStub, null, 2));
    lines.push('\n```\n\n');
  }
  if (spec.recordShape.notes) {
    lines.push(heading(3, 'Notes'));
    lines.push(`${spec.recordShape.notes.map((n) => `- ${n}`).join('\n')}\n\n`);
  }

  if (spec.persistence) {
    lines.push(heading(2, 'Persistence'));
    for (const [name, entry] of Object.entries(spec.persistence)) {
      lines.push(`- **\`${name}\`** — \`${entry.method}\``);
      if (entry.options) {
        lines.push(`  - Options: ${entry.options.map((o) => `\`${o}\``).join(', ')}`);
      }
    }
    lines.push('\n');
  }

  if (spec.react) {
    lines.push(heading(2, 'React (`dignity.js/react`)'));
    lines.push(`Entry: \`${spec.react.entrypoint}\`\n\n`);
    lines.push(`${(spec.react.hooks || []).map((h) => `- \`${h}\``).join('\n')}\n\n`);
  }

  if (spec.signaling) {
    lines.push(heading(2, 'Signaling'));
    lines.push(`- Cloudflare: ${spec.signaling.defaults.cloudflare}\n`);
    lines.push(`- Fallback: ${spec.signaling.defaults.fallback}\n`);
    lines.push(`- Factory: \`${spec.signaling.customization.factory}\`\n`);
    lines.push(`- Overrides: ${spec.signaling.customization.override.map((o) => `\`${o}\``).join(', ')}\n\n`);
  }

  if (spec.messageSecurity) {
    lines.push(heading(2, 'Message security defaults'));
    lines.push('```json\n');
    lines.push(JSON.stringify(spec.messageSecurity.defaults, null, 2));
    lines.push('\n```\n\n');
    lines.push(`- Broadcast: ${spec.messageSecurity.broadcast.encryption}; scopes via \`broadcastPasswords\`\n`);
    lines.push(`- Direct: ${spec.messageSecurity.direct.encryption}\n`);
    lines.push(`- PoW: ${spec.messageSecurity.pow.algorithm} (\`${spec.messageSecurity.pow.config.join('`, `')}\`)\n\n`);
  }

  lines.push(heading(2, 'Package exports'));
  lines.push('See [`src/index.js`](../src/index.js) for the full public surface (`DignityP2P`, signaling, CQRS, apps manifest, etc.).\n\n');
  lines.push(`Package version: **${pkg.version}** (spec ${spec.version}).\n`);

  return lines.join('');
}

const markdown = buildMarkdown();
fs.writeFileSync(outPath, markdown, 'utf8');
console.log(`Wrote ${outPath} (${markdown.length} bytes)`);
